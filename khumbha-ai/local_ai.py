"""Khumbha AI — Local AI provider bridge.

This module is the *real* connector between the Khumbha AI phase and AI models
running on the user's own device. It is deliberately provider-agnostic:

  * ``ollama``  — native Ollama API (``/api/tags``, ``/api/chat``)
  * ``openai``  — any OpenAI-compatible server (LM Studio, llama.cpp server,
                  vLLM, text-generation-webui, LocalAI, ...)

Design rules
------------
1. **Local-first.** The bridge binds to loopback by default and never proxies a
   local model through the VM. The VM owns market data, auth and persistence;
   the local device owns inference.
2. **No fabricated data.** This module only reports what a provider actually
   answered. An unreachable provider stays unreachable with its real error.
3. **Advisory only.** ``analyze()`` is an explainer, not a trading engine. The
   system prompt forbids recommendations, targets and invented facts.
4. **No prompt logging.** Only metadata (provider, model, latency, sizes) is
   logged. Message content and context stay in memory.
5. **User-controlled config.** Provider URLs/models are stored in a local JSON
   file (``local-ai.json``) that is gitignored. Nothing is sent to the VM.

The module uses only the Python standard library for HTTP so the runtime keeps
its small dependency set (fastapi/uvicorn/numpy/psutil).
"""
from __future__ import annotations

