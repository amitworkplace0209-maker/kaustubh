# Small helpers
# ---------------------------------------------------------------------------
def _utc_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def _as_float(value: Any, default: float, minimum: float, maximum: float) -> float:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return default
    return max(minimum, min(maximum, number))


def _as_int(value: Any, default: int, minimum: int, maximum: int) -> int:
    try:
        number = int(value)
    except (TypeError, ValueError):
        return default
    return max(minimum, min(maximum, number))


def _clean_text(value: Any, limit: int = 4000) -> str:
    """Strip control characters and cap length. Used for provider errors/names."""
    text = str(value or "")
    text = re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]", " ", text)
    return text[:limit]


def normalize_base_url(value: str) -> str:
    """Validate a provider URL and return it without a trailing slash.

    Only http/https is accepted. Link-local metadata hosts are refused so a
    compromised page cannot use the bridge as a cloud-metadata proxy.
    """
    raw = str(value or "").strip()
    if not raw:
        raise ValueError("base URL is required")
    if len(raw) > 2048:
        raise ValueError("base URL is too long")
    parsed = urllib.parse.urlsplit(raw)
    if parsed.scheme not in ("http", "https"):
        raise ValueError("base URL must start with http:// or https://")
    if not parsed.netloc or not parsed.hostname:
        raise ValueError("base URL must include a host")
    if parsed.username or parsed.password:
        raise ValueError("base URL must not contain credentials")
    host = parsed.hostname.lower()
    if host in {"169.254.169.254", "metadata.google.internal"}:
        raise ValueError("metadata hosts are not allowed")
    path = parsed.path.rstrip("/")
    return urllib.parse.urlunsplit((parsed.scheme, parsed.netloc, path, "", ""))


def _join(base: str, path: str) -> str:
    return f"{base.rstrip('/')}/{path.lstrip('/')}"


def _openai_urls(base: str, suffix: str) -> list[str]:
    """Return candidate URLs for OpenAI-compatible servers.

    LM Studio normally exposes ``/v1``; llama.cpp accepts both ``/v1`` and the
    bare root. We try the explicit base first, then the ``/v1`` variant.
    """
    base = base.rstrip("/")
    suffix = suffix.lstrip("/")
    if base.endswith("/v1"):
        return [_join(base, suffix)]
    return [_join(base, suffix), _join(base, f"v1/{suffix}")]


def _http_json(
    method: str,
    url: str,
    payload: dict[str, Any] | None = None,
    timeout: float = 10.0,
) -> tuple[int, Any, str | None]:
    """Perform one HTTP request and return ``(status, parsed_json, error)``.

    Never raises for network/HTTP errors; the caller decides how to surface
    them. The response body is capped so a misbehaving server cannot exhaust
    memory.
    """
    data = None
    headers = {"Accept": "application/json"}
    if payload is not None:
        data = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        headers["Content-Type"] = "application/json"
    request = urllib.request.Request(url, data=data, headers=headers, method=method)
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            raw = response.read(MAX_RESPONSE_BYTES + 1)
            if len(raw) > MAX_RESPONSE_BYTES:
                return response.status, None, "response too large"
            if not raw:
                return response.status, None, None
            try:
                return response.status, json.loads(raw.decode("utf-8", "replace")), None
            except json.JSONDecodeError:
                return response.status, None, "provider returned non-JSON"
    except urllib.error.HTTPError as exc:
        body = ""
        try:
            body = exc.read(2048).decode("utf-8", "replace")
        except Exception:  # noqa: BLE001 - best-effort error text only
            body = ""
        detail = _clean_text(body, 300)
        return exc.code, None, f"HTTP {exc.code}{': ' + detail if detail else ''}"
    except urllib.error.URLError as exc:
        reason = getattr(exc, "reason", exc)
        return 0, None, _clean_text(reason, 300)
    except TimeoutError:
        return 0, None, f"timed out after {timeout:g}s"
    except Exception as exc:  # noqa: BLE001 - network boundary
        return 0, None, _clean_text(exc, 300)


