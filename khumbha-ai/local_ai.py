# Registry
# ---------------------------------------------------------------------------
class ProviderRegistry:
    """Thread-safe provider config + probe cache."""

    def __init__(self, config_path: str | Path | None = None) -> None:
        self.path = Path(config_path) if config_path else default_config_path()
        self._lock = threading.RLock()
        self._cache: dict[str, dict[str, Any]] = {}
        self._config = self._load()

    # -- persistence -------------------------------------------------------
    def _load(self) -> dict[str, Any]:
        config = default_config()
        try:
            if self.path.exists():
                raw = json.loads(self.path.read_text(encoding="utf-8"))
                if isinstance(raw, dict):
                    if isinstance(raw.get("defaults"), dict):
                        config["defaults"].update(
                            {k: v for k, v in raw["defaults"].items() if k in config["defaults"]}
                        )
                    if isinstance(raw.get("providers"), dict):
                        for pid, stored in raw["providers"].items():
                            if pid in config["providers"] and isinstance(stored, dict):
                                config["providers"][pid].update(
                                    {k: v for k, v in stored.items() if k in config["providers"][pid]}
                                )
        except Exception as exc:  # noqa: BLE001 - corrupt config must not stop the bridge
            logger.warning("local-ai config ignored (%s)", _clean_text(exc, 200))
        return self._validate_config(config)

    def _validate_config(self, config: dict[str, Any]) -> dict[str, Any]:
        defaults = config.get("defaults") or {}
        config["defaults"] = {
            "provider": str(defaults.get("provider") or "ollama"),
            "model": str(defaults.get("model") or ""),
            "temperature": _as_float(defaults.get("temperature"), 0.2, 0.0, 2.0),
            "max_tokens": _as_int(defaults.get("max_tokens"), 900, 64, 8192),
        }
        providers = config.get("providers") or {}
        for pid, provider in providers.items():
            provider["id"] = pid
            provider["kind"] = "ollama" if provider.get("kind") == "ollama" else "openai"
            provider["label"] = _clean_text(provider.get("label") or pid, 80)
            provider["enabled"] = bool(provider.get("enabled"))
            provider["model"] = str(provider.get("model") or "")
            try:
                provider["base_url"] = normalize_base_url(provider.get("base_url") or "")
            except ValueError:
                provider["base_url"] = str(provider.get("base_url") or "").strip()
        if config["defaults"]["provider"] not in providers:
            config["defaults"]["provider"] = next(iter(providers), "ollama")
        return config

    def _save(self) -> None:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        temporary = self.path.with_suffix(".tmp")
        temporary.write_text(json.dumps(self._config, indent=2), encoding="utf-8")
        temporary.replace(self.path)
        try:
            os.chmod(self.path, 0o600)
        except OSError:
            pass

    # -- config access -----------------------------------------------------
    @property
    def defaults(self) -> dict[str, Any]:
        with self._lock:
            return dict(self._config["defaults"])

    def providers(self) -> list[dict[str, Any]]:
        with self._lock:
            return [dict(p) for p in self._config["providers"].values()]

    def provider(self, provider_id: str) -> dict[str, Any]:
        with self._lock:
            provider = self._config["providers"].get(provider_id)
            if not provider:
                raise KeyError(f"unknown provider: {provider_id}")
            return dict(provider)

    def update_provider(self, provider_id: str, payload: dict[str, Any]) -> dict[str, Any]:
        with self._lock:
            provider = self._config["providers"].get(provider_id)
            if not provider:
                raise KeyError(f"unknown provider: {provider_id}")

            if "baseUrl" in payload or "base_url" in payload:
                raw_url = payload.get("baseUrl", payload.get("base_url"))
                provider["base_url"] = normalize_base_url(str(raw_url or "")) if str(raw_url or "").strip() else ""
            if "kind" in payload:
                provider["kind"] = "ollama" if payload["kind"] == "ollama" else "openai"
            if "label" in payload:
                provider["label"] = _clean_text(payload["label"], 80)
            if "enabled" in payload:
                provider["enabled"] = bool(payload["enabled"])
            if "model" in payload:
                provider["model"] = str(payload.get("model") or "")[:200]

            self._cache.pop(provider_id, None)
            self._save()
            return dict(provider)

    def update_defaults(self, payload: dict[str, Any]) -> dict[str, Any]:
        with self._lock:
            defaults = self._config["defaults"]
            if "provider" in payload:
                candidate = str(payload["provider"] or "")
                if candidate and candidate not in self._config["providers"]:
                    raise KeyError(f"unknown provider: {candidate}")
                defaults["provider"] = candidate or defaults["provider"]
            if "model" in payload:
                defaults["model"] = str(payload["model"] or "")[:200]
            if "temperature" in payload:
                defaults["temperature"] = _as_float(payload["temperature"], defaults["temperature"], 0.0, 2.0)
            if "maxTokens" in payload or "max_tokens" in payload:
                defaults["max_tokens"] = _as_int(
                    payload.get("maxTokens", payload.get("max_tokens")),
                    defaults["max_tokens"],
                    64,
                    8192,
                )
            self._save()
            return dict(defaults)

    # -- probing -----------------------------------------------------------
    def _probe_uncached(self, provider: dict[str, Any], timeout: float) -> dict[str, Any]:
        base = provider.get("base_url") or ""
        if not base:
            return {"reachable": False, "models": [], "error": "no base URL configured", "checkedAt": _utc_iso()}
        try:
            normalize_base_url(base)
        except ValueError as exc:
            return {"reachable": False, "models": [], "error": str(exc), "checkedAt": _utc_iso()}

        kind = provider.get("kind") or "openai"
        candidates: list[tuple[str, str]] = []
        if kind == "ollama":
            candidates.append((_join(base, "/api/tags"), "ollama"))
            candidates.extend((url, "openai") for url in _openai_urls(base, "/models"))
        else:
            candidates.extend((url, "openai") for url in _openai_urls(base, "/models"))

        last_error = "provider unreachable"
        for url, response_kind in candidates:
            status, payload, error = _http_json("GET", url, timeout=timeout)
            if status and 200 <= status < 300 and payload is not None:
                models = normalize_models(response_kind, payload)
                return {
                    "reachable": True,
                    "models": models,
                    "error": None,
                    "checkedAt": _utc_iso(),
                }
            if error:
                last_error = error
        return {"reachable": False, "models": [], "error": last_error, "checkedAt": _utc_iso()}

    def probe(self, provider_id: str, *, timeout: float = DEFAULT_PROBE_TIMEOUT, force: bool = True) -> dict[str, Any]:
        provider = self.provider(provider_id)
        with self._lock:
            cached = self._cache.get(provider_id)
            if not force and cached and time.time() - cached["ts"] < PROBE_TTL_SEC:
                return {**cached["result"], "cached": True}
        result = self._probe_uncached(provider, timeout)
        with self._lock:
            self._cache[provider_id] = {"ts": time.time(), "result": result}
        logger.info(
            "probe provider=%s reachable=%s models=%d error=%s",
            provider_id,
            result["reachable"],
            len(result["models"]),
            _clean_text(result.get("error"), 120),
        )
        return result

    def snapshot(self, *, probe: bool = True, timeout: float = DEFAULT_PROBE_TIMEOUT) -> dict[str, Any]:
        providers = self.providers()
        enabled = [p for p in providers if p.get("enabled")]
        results: dict[str, dict[str, Any]] = {}

        if enabled:
            # Always surface the last known real result. With `probe=True`,
            # still call probe() so an entry older than PROBE_TTL_SEC is
            # refreshed; probe(force=False) returns a fresh cached result
            # without touching the provider.
            with self._lock:
                for provider in enabled:
                    cached = self._cache.get(provider["id"])
                    if cached:
                        results[provider["id"]] = {**cached["result"], "cached": True}
            pending = enabled if probe else []
            if pending:
                with ThreadPoolExecutor(max_workers=min(4, len(pending))) as pool:
                    futures = {
                        pool.submit(self.probe, provider["id"], timeout=timeout, force=False): provider["id"]
                        for provider in pending
                    }
                    for future, provider_id in futures.items():
                        try:
                            results[provider_id] = future.result()
                        except Exception as exc:  # noqa: BLE001 - probe boundary
                            results[provider_id] = {
                                "reachable": False,
                                "models": [],
                                "error": _clean_text(exc, 200),
                                "checkedAt": _utc_iso(),
                            }

        public: list[dict[str, Any]] = []
        for provider in providers:
            result = results.get(provider["id"], {})
            public.append(
                {
                    "id": provider["id"],
                    "label": provider["label"],
                    "kind": provider["kind"],
                    "baseUrl": provider["base_url"],
                    "enabled": provider["enabled"],
                    "model": provider["model"],
                    "reachable": bool(result.get("reachable")) if provider["enabled"] else False,
                    "error": result.get("error") if provider["enabled"] else None,
                    "models": result.get("models", []) if provider["enabled"] else [],
                    "checkedAt": result.get("checkedAt") if provider["enabled"] else None,
                    "cached": bool(result.get("cached")) if provider["enabled"] else False,
                }
            )

        return {
            "bridge": True,
            "version": BRIDGE_VERSION,
            "providers": public,
            "defaults": self.defaults,
            "generatedAt": _utc_iso(),
        }

    def models(self, *, probe: bool = True) -> list[dict[str, Any]]:
        snapshot = self.snapshot(probe=probe)
        flat: list[dict[str, Any]] = []
        for provider in snapshot["providers"]:
            for model in provider["models"]:
                flat.append({**model, "provider": provider["id"], "providerLabel": provider["label"]})
        return flat

    def summary(self) -> dict[str, Any]:
        with self._lock:
            providers = list(self._config["providers"].values())
            cache = dict(self._cache)
        reachable = sum(
            1
            for p in providers
            if p.get("enabled") and cache.get(p["id"], {}).get("result", {}).get("reachable")
        )
        return {
            "bridge": True,
            "version": BRIDGE_VERSION,
            "providers": len(providers),
            "providersEnabled": sum(1 for p in providers if p.get("enabled")),
            "providersReachable": reachable,
            "defaultProvider": self.defaults["provider"],
            "defaultModel": self.defaults["model"],
        }

    # -- inference ---------------------------------------------------------
    def _resolve(self, provider_id: str | None, model: str | None) -> tuple[dict[str, Any], str]:
        with self._lock:
            providers = self._config["providers"]
            defaults = self._config["defaults"]
            pid = (provider_id or defaults.get("provider") or "").strip()
            provider = providers.get(pid)
            if provider is None:
                provider = next((p for p in providers.values() if p.get("enabled") and p.get("base_url")), None)
            if provider is None:
                raise ValueError("no local AI provider is configured")
            if not provider.get("enabled"):
                raise ValueError(f"provider '{provider['id']}' is disabled")
            if not provider.get("base_url"):
                raise ValueError(f"provider '{provider['id']}' has no base URL")
            chosen_model = (model or provider.get("model") or defaults.get("model") or "").strip()

        if not chosen_model:
            probe = self.probe(provider["id"], force=False)
            if not probe.get("reachable"):
                raise ValueError(
                    f"provider '{provider['id']}' is unreachable: {probe.get('error') or 'unknown error'}"
                )
            models = probe.get("models") or []
            if len(models) == 1:
                chosen_model = models[0]["id"]
            elif models:
                names = ", ".join(m["id"] for m in models[:8])
                raise ValueError(
                    f"no model selected for '{provider['id']}'. Choose one of: {names}"
                )
            else:
                raise ValueError(
                    f"provider '{provider['id']}' is reachable but exposes no models. "
                    "Download a model in the provider first."
                )
        return provider, chosen_model

    def chat(
        self,
        messages: Any,
        *,
        provider_id: str | None = None,
        model: str | None = None,
        temperature: float | None = None,
        max_tokens: int | None = None,
        timeout: float | None = None,
    ) -> dict[str, Any]:
        cleaned = validate_messages(messages)
        provider, chosen_model = self._resolve(provider_id, model)
        defaults = self.defaults
        temp = _as_float(temperature if temperature is not None else defaults["temperature"], 0.2, 0.0, 2.0)
        tokens = _as_int(max_tokens if max_tokens is not None else defaults["max_tokens"], 900, 64, 8192)
        wait = _as_float(timeout if timeout is not None else DEFAULT_CHAT_TIMEOUT, DEFAULT_CHAT_TIMEOUT, 5, 300)

        started = time.perf_counter()
        if provider["kind"] == "ollama":
            url = _join(provider["base_url"], "/api/chat")
            payload = {
                "model": chosen_model,
                "messages": cleaned,
                "stream": False,
                "options": {"temperature": temp, "num_predict": tokens},
            }
            attempts = [(url, "ollama")]
        else:
            payload = {
                "model": chosen_model,
                "messages": cleaned,
                "temperature": temp,
                "max_tokens": tokens,
                "stream": False,
            }
            attempts = [(url, "openai") for url in _openai_urls(provider["base_url"], "/chat/completions")]

        last_error = "provider unreachable"
        for url, response_kind in attempts:
            status, body, error = _http_json("POST", url, payload=payload, timeout=wait)
            if status and 200 <= status < 300 and body is not None:
                try:
                    content, usage = _extract_content(response_kind, body)
                except ValueError as exc:
                    last_error = str(exc)
                    continue
                latency_ms = round((time.perf_counter() - started) * 1000, 2)
                logger.info(
                    "chat provider=%s model=%s latency_ms=%.2f prompt_chars=%d",
                    provider["id"],
                    chosen_model,
                    latency_ms,
                    sum(len(m["content"]) for m in cleaned),
                )
                return {
                    "provider": provider["id"],
                    "providerLabel": provider["label"],
                    "model": chosen_model,
                    "content": content,
                    "usage": usage,
                    "latencyMs": latency_ms,
                    "createdAt": _utc_iso(),
                }
            if error:
                last_error = error

        raise RuntimeError(f"local provider '{provider['id']}' failed: {last_error}")

    def analyze(
        self,
        kind: str,
        context: dict[str, Any],
        *,
        question: str | None = None,
        provider_id: str | None = None,
        model: str | None = None,
        temperature: float | None = None,
        max_tokens: int | None = None,
    ) -> dict[str, Any]:
        messages = build_analysis_messages(kind, context, question)
        result = self.chat(
            messages,
            provider_id=provider_id,
            model=model,
            temperature=temperature,
            max_tokens=max_tokens,
        )
        return {
            **result,
            "kind": kind,
            "groundedFields": sorted(str(key) for key in context.keys()),
            "contextChars": len(json.dumps(context, ensure_ascii=False, sort_keys=True, default=str)),
            "disclaimer": DISCLAIMER,
        }
